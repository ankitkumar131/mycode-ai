#!/usr/bin/env node
/**
 * Refresh the bundled /graphify skill from upstream (Graphify-Labs/graphify, Apache-2.0).
 * Usage: node scripts/sync-graphify-skill.mjs [ref]     (default ref: v8)
 * Writes packages/core/src/skills/bundled/graphify.ts
 */
import { writeFileSync, mkdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const ref = process.argv[2] ?? 'v8';
const repo = 'Graphify-Labs/graphify';
const headers = { 'User-Agent': 'mycode-cli', Accept: 'application/vnd.github+json' };
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

async function file(path) {
  const r = await fetch(`https://api.github.com/repos/${repo}/contents/${path}?ref=${ref}`, { headers });
  if (!r.ok) throw new Error(`HTTP ${r.status} for ${path}`);
  const j = await r.json();
  return Buffer.from(j.content, 'base64').toString('utf-8');
}
async function list(path) {
  const r = await fetch(`https://api.github.com/repos/${repo}/contents/${path}?ref=${ref}`, { headers });
  if (!r.ok) throw new Error(`HTTP ${r.status} for ${path}`);
  return (await r.json()).filter(e => e.type === 'file').map(e => e.name);
}

const files = {};
let skillMd = await file('graphify/skill.md');
// Make the frontmatter carry our metadata while keeping upstream's text verbatim.
skillMd = skillMd.replace(/^---\n([\s\S]*?)\n---/, (_m, fm) =>
  `---\n${fm}\nversion: upstream-${ref}\ncategory: code-intelligence\ntags: [knowledge-graph, architecture, codebase, query]\nargument-hint: "[path|url|query \\"question\\"] [--update|--mode deep]"\nsource: https://github.com/${repo}\nlicense: Apache-2.0\n---`
);
files['SKILL.md'] = skillMd;
for (const name of await list('graphify/skills/agents/references')) {
  files[`references/${name}`] = await file(`graphify/skills/agents/references/${name}`);
}
files['NOTICE'] = `The graphify skill (SKILL.md and references/) is bundled verbatim from\nhttps://github.com/${repo} (ref ${ref}) and is licensed under the Apache License 2.0.\nCopyright Graphify Labs. See https://github.com/${repo}/blob/${ref}/LICENSE\n`;

const out = `/* AUTO-GENERATED by scripts/sync-graphify-skill.mjs — do not edit by hand.
 * Source: https://github.com/${repo} @ ${ref}  (Apache-2.0)
 * Synced: ${new Date().toISOString().slice(0, 10)}
 */
export const GRAPHIFY_SKILL_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};
`;
const dest = join(dirname(fileURLToPath(import.meta.url)), '..', 'packages', 'core', 'src', 'skills', 'bundled', 'graphify.ts');
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out);
console.log(`Wrote ${dest}: ${Object.keys(files).length} files, ${(out.length / 1024).toFixed(0)} KB`);
